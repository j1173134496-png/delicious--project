#!/usr/bin/env node

/** Offline Service smoke test. No wx global, network, or npm dependency. */
const assert = require('assert')
const storage = require('../miniprogram/services/storageService')
const userService = require('../miniprogram/services/userService')
const catService = require('../miniprogram/services/catService')
const chatService = require('../miniprogram/services/chatService')
const recipeService = require('../miniprogram/services/recipeService')
const albumService = require('../miniprogram/services/albumService')
const feedbackService = require('../miniprogram/services/feedbackService')
const { FORM_META, CAT_STATES, getFormAsset } = require('../miniprogram/models/cat')
const { dateString } = require('../miniprogram/utils/dateUtil')
const { withImageFlag, markImageError, isImagePath } = require('../miniprogram/utils/mediaUtil')
const { LIMITS } = require('../miniprogram/utils/limits')

function check(condition, message) {
  assert.ok(condition, message)
}

async function main() {
  storage.clear()
  const first = storage.initialize()
  check(first && first.initialized, 'storage initializes')
  check(first.schemaVersion === 4 && first.schemaName === '1.3', 'storage uses v1.3 schema')
  const initialUser = userService.getCurrentUser()
  const initialCat = catService.getCat()
  check(initialUser.nickname === '小主人', 'default user is available')
  check(initialCat.level === 1 && initialCat.feedCount === 0, 'default cat is available')
  const formKeys = Object.keys(FORM_META)
  const stateKeys = Object.keys(CAT_STATES)
  check(formKeys.length === 4 && stateKeys.length === 5 && stateKeys.indexOf('sleeping') >= 0, 'cat form/state metadata has four forms and five states')
  formKeys.forEach((form) => stateKeys.forEach((state) => {
    const asset = getFormAsset(form, state)
    check(asset.formKey === form && asset.stateKey === state, `asset matrix resolves ${form}/${state}`)
    const expectedFallback = state === 'idle' ? 'state' : 'idle'
    check(asset.imagePath === FORM_META[form].imagePath && asset.fallback === expectedFallback, `${state} asset resolves or falls back to idle for ${form}`)
    check(typeof asset.animationClass === 'string' && asset.animationClass.indexOf(`cat-display--${state}`) === 0, `state animation class resolves ${form}/${state}`)
  }))
  const unknownAsset = getFormAsset('missing-form', 'missing-state')
  check(unknownAsset.formKey === 'baby' && unknownAsset.stateKey === 'idle' && unknownAsset.fallback === 'state', 'unknown form/state falls back to baby idle')
  let componentDefinition = null
  global.Component = (definition) => { componentDefinition = definition }
  const componentPath = require.resolve('../miniprogram/components/cat-display/cat-display.js')
  delete require.cache[componentPath]
  require(componentPath)
  delete global.Component
  const componentContext = { data: Object.assign({}, componentDefinition.data), setData(update) { this.data = Object.assign({}, this.data, update) } }
  componentDefinition.observers['cat.currentForm, cat.stateKey, state'].call(componentContext, 'baby', 'happy', 'happy')
  check(componentContext.data.stateClass === 'cat-display--happy' && componentContext.data.formName === FORM_META.baby.name, 'cat component shares form/state metadata')
  componentDefinition.methods.onImageError.call(componentContext)
  check(!componentContext.data.hasImage && componentContext.data.assetFallback === 'emoji', 'cat component image error falls back to Emoji')
  componentDefinition.observers['cat.currentForm, cat.stateKey, state'].call(componentContext, 'baby', 'happy', 'happy')
  check(!componentContext.data.hasImage, 'cat component does not retry the same failed image path')
  componentDefinition.observers['cat.currentForm, cat.stateKey, state'].call(componentContext, 'genki', 'idle', 'idle')
  check(componentContext.data.hasImage && componentContext.data.imagePath === FORM_META.genki.imagePath, 'cat component retries only after asset path changes')
  const second = storage.initialize()
  check(second.schemaVersion === first.schemaVersion, 'initialize is idempotent')
  check(userService.getCurrentUser().userId === initialUser.userId, 'initialize preserves legal user')

  storage.set(storage.KEYS.META, { schemaVersion: 3, schemaName: '1.2', initializedAt: 123 })
  storage.set(storage.KEYS.USER, { userId: 'preserved-user', nickname: '保留资料' })
  storage.set(storage.KEYS.CHATS, { broken: true })
  storage.set(storage.KEYS.CAT, { level: 'bad', mood: 999, hunger: -10, todayFeedCount: 99 })
  storage.set(storage.KEYS.RECIPES, [{ recipeId: 'legacy-recipe', name: '旧菜谱' }])
  storage.set(storage.KEYS.PHOTOS, [{ photoId: 'legacy-photo', imagePath: 'emoji:🌷' }])
  storage.set(storage.KEYS.SETTINGS, { emotionCareEnabled: false, notificationsEnabled: false, albumSignature: '旧签名' })
  storage.set(storage.KEYS.INVITE, { code: 'ABC234', createdAt: 123 })
  storage.set(storage.KEYS.FEEDBACK, [{ feedbackId: 'legacy-feedback', category: 'bug', content: '旧反馈', createdAt: 123, status: 'saved_local' }])
  const migration = storage.initialize()
  check(migration.migrated && migration.schemaVersion === 4 && migration.schemaName === '1.3', 'v1.2 data migrates to v1.3')
  check(migration.repaired >= 1 && migration.deduped === 0 && migration.failed === 0, 'migration exposes repair counters')
  check(migration.dropReasons && migration.failedReasons && typeof migration.dropReasons === 'object', 'migration exposes deterministic drop/failure reason maps')
  check(userService.getCurrentUser().userId === 'preserved-user' && userService.getCurrentUser().nickname === '保留资料', 'migration preserves legal user fields')
  check(Array.isArray(storage.get(storage.KEYS.CHATS, null)), 'migration repairs broken collections')
  check(storage.list(storage.KEYS.RECIPES)[0].recipeId === 'legacy-recipe' && storage.list(storage.KEYS.PHOTOS)[0].photoId === 'legacy-photo', 'migration preserves recipe and photo collections')
  check(storage.get(storage.KEYS.INVITE, {}).code === 'ABC234', 'migration preserves invite data')
  check(feedbackService.list().length === 1 && feedbackService.list()[0].feedbackId === 'legacy-feedback', 'schema migration preserves feedback collection')
  const repairedCat = catService.getCat()
  check(repairedCat.level >= 1 && repairedCat.level <= 4 && repairedCat.mood <= 100 && repairedCat.hunger >= 0 && repairedCat.todayFeedCount <= 3, 'migration normalizes cat bounds')
  check(userService.getSettings().emotionCareEnabled === false && userService.getSettings().notificationsEnabled === false && userService.getSettings().albumSignature === '旧签名', 'migration preserves legal settings')

  storage.set(storage.KEYS.RECIPES, [{ recipeId: 'same', name: '旧', createdAt: 1 }, { recipeId: 'same', name: '新', createdAt: 2 }])
  storage.set(storage.KEYS.PHOTOS, [{ photoId: 'p', imagePath: 'emoji:🌷', createdAt: 1 }, { photoId: 'p', imagePath: 'emoji:🌷', createdAt: 2 }])
  const dedupeFirst = storage.initialize()
  const dedupeSecond = storage.initialize()
  check(storage.list(storage.KEYS.RECIPES).length === 1 && storage.list(storage.KEYS.RECIPES)[0].name === '新', 'recipe duplicate migration keeps latest complete record')
  check(storage.list(storage.KEYS.PHOTOS).length === 1 && storage.list(storage.KEYS.PHOTOS)[0].createdAt === 2, 'photo duplicate migration keeps latest record')
  check(dedupeFirst.migrated && dedupeFirst.deduped === 2 && !dedupeSecond.migrated && dedupeSecond.deduped === 0, 'dedupe migration is idempotent')

  storage.clear()
  storage.initialize()
  const activeUser = userService.getCurrentUser()
  const historicalDate = dateString(new Date(Date.now() - 366 * 86400000))
  const validAnniversary = userService.setAnniversaryDate(historicalDate)
  check(validAnniversary.ok && userService.getAnniversaryDate() === historicalDate, 'valid anniversary date saves')
  const invalidAnniversary = userService.setAnniversaryDate('2024-02-31')
  check(!invalidAnniversary.ok && userService.getAnniversaryDate() === historicalDate, 'invalid anniversary date is rejected')
  const futureAnniversary = userService.setAnniversaryDate('2999-01-01')
  check(!futureAnniversary.ok && userService.getAnniversaryDate() === historicalDate, 'future anniversary date is rejected')

  const recipes = recipeService.ensureDefaults()
  check(recipes.length === 12, 'default recipe count is 12')
  const custom = recipeService.create({ name: '离线烟火', category: 'custom' })
  check(recipeService.get(custom.recipeId).name === '离线烟火', 'recipe create/get works')
  const duplicateRecipe = recipeService.create({ recipeId: custom.recipeId, name: '重复菜谱', category: 'custom' })
  check(!duplicateRecipe && recipeService.getLastError().code === 'duplicate_recipe' && recipeService.list().filter((item) => item.recipeId === custom.recipeId).length === 1, 'recipe service rejects duplicate recipe id')
  const savedRecipesBeforeLimit = recipeService.list()
  storage.set(storage.KEYS.RECIPES, Array.from({ length: LIMITS.RECIPE_TOTAL_RECORDS }, (_, index) => ({ recipeId: `limit-recipe-${index}`, name: `容量菜谱${index}`, createdAt: index + 1 })))
  storage.initialize()
  const overRecipeLimit = recipeService.create({ name: '超过容量的菜谱' })
  check(!overRecipeLimit && recipeService.getLastError().code === 'recipe_limit', 'recipe total limit returns visible code')
  storage.set(storage.KEYS.RECIPES, savedRecipesBeforeLimit)
  storage.initialize()
  const rated = recipeService.update(custom.recipeId, { rating: 5, review: '好吃' })
  check(rated.rating === 5 && rated.review === '好吃', 'recipe update works')
  check(recipeService.toggleLike(custom.recipeId).likes.length === 1, 'recipe like works')

  const invalidFeedback = feedbackService.submit({ category: 'unknown', content: '太短' })
  check(!invalidFeedback.ok && invalidFeedback.code === 'invalid_category', 'feedback rejects invalid category')
  const shortFeedback = feedbackService.submit({ category: 'bug', content: '短' })
  check(!shortFeedback.ok && shortFeedback.code === 'content_too_short', 'feedback rejects short content')
  const longFeedback = feedbackService.submit({ category: 'bug', content: 'x'.repeat(501) })
  check(!longFeedback.ok && longFeedback.code === 'content_too_long', 'feedback rejects overlong content')
  const savedFeedback = feedbackService.submit({ category: 'feature', content: '希望可以看到更多温柔的成长提示', contact: 'offline@example.invalid' })
  check(savedFeedback.ok && savedFeedback.record.status === 'saved_local' && feedbackService.list().length === 1, 'feedback saves locally with explicit status')
  check(feedbackService.formatForCopy(savedFeedback.record).indexOf('尚未发送到服务器') >= 0, 'feedback copy text states it is not sent')

  const todayDate = dateString(new Date())
  userService.setAnniversaryDate(todayDate)
  storage.set(storage.KEYS.CAT, { level: 1, feedCount: 29, chatCount: 49, exp: 0, mood: 50, hunger: 50, todayFeedCount: 0, lastFeedTime: 0 })
  const levelOneFeed = catService.feed()
  check(levelOneFeed.ok && levelOneFeed.cat.level === 1 && !levelOneFeed.transition, 'level 1 waits for both feed and chat conditions')
  const levelTwoTransition = catService.recordChat()
  check(levelTwoTransition.level === 2 && levelTwoTransition.transition && levelTwoTransition.transition.from === 1 && levelTwoTransition.transition.to === 2, 'level 1 upgrades at feed 30 and chat 50')
  const levelTwoProgress = catService.getProgress()
  check(levelTwoProgress.nextFormName === 'JK 猫猫' && levelTwoProgress.unlockedRecipesRemaining === 10 && levelTwoProgress.feedRemaining === 70, 'level 2 progress explains recipe and feed requirements')
  const missingRecipes = catService.recordChat()
  check(missingRecipes.level === 2 && !missingRecipes.transition, 'level 2 does not upgrade without ten unlocked recipes')
  for (let index = 0; index < 10; index += 1) recipeService.create({ name: `已解锁菜品${index + 1}`, photos: [`emoji:🍲${index}`] })
  storage.set(storage.KEYS.CAT, Object.assign({}, catService.getCat(), { feedCount: 100 }))
  const levelThreeTransition = catService.recordChat()
  check(levelThreeTransition.level === 3 && levelThreeTransition.transition && levelThreeTransition.transition.from === 2 && levelThreeTransition.transition.to === 3, 'level 2 upgrades with feed 100 and ten unlocked recipes')
  const levelThreeProgress = catService.getProgress()
  check(levelThreeProgress.nextFormName === '花嫁猫' && levelThreeProgress.anniversaryRemaining >= 365 && levelThreeProgress.percent === 0, 'level 3 progress waits for 365 anniversary days')
  const missingAnniversary = catService.recordChat()
  check(missingAnniversary.level === 3 && !missingAnniversary.transition, 'level 3 does not upgrade before anniversary')
  userService.setAnniversaryDate(historicalDate)
  const levelFourTransition = catService.recordChat()
  check(levelFourTransition.level === 4 && levelFourTransition.transition && levelFourTransition.transition.from === 3 && levelFourTransition.transition.to === 4, 'level 3 upgrades after 365 anniversary days')
  check(catService.getProgress().complete && catService.getProgress().next === null, 'level 4 reports completed progress')
  storage.set(storage.KEYS.CAT, { level: 4, feedCount: 0, chatCount: 0, exp: 0, mood: 50, hunger: 50, todayFeedCount: 0, lastFeedTime: 0 })
  check(catService.getCat().level === 4 && catService.getProgress().current === 4, 'existing level 4 data never downgrades')

  const remotePath = ['https', '://example.invalid/migrated.png'].join('')
  const dataPath = ['data', ':image/png;base64,migrated'].join('')
  const blockedPaths = [remotePath, dataPath, 'blob:migrated', 'unknown://migrated', 'emoji:🌷']
  const localPaths = ['local://migrated', 'wxfile://migrated', 'file:///migrated', 'temp://migrated', '/migrated.png']
  check(blockedPaths.every((path) => !isImagePath(path)), 'media presenter rejects remote/data/blob/unknown and emoji paths')
  check(localPaths.every((path) => isImagePath(path)), 'media presenter accepts local, wxfile, file, temp and absolute paths')
  storage.set(storage.KEYS.PHOTOS, blockedPaths.slice(0, 4).map((imagePath, index) => ({ photoId: `migrated-${index}`, imagePath, date: '2026-09-27', createdAt: index + 1 })))
  storage.initialize()
  const migratedPaths = storage.list(storage.KEYS.PHOTOS).map((photo) => photo.imagePath)
  check(migratedPaths.length === 4 && migratedPaths.every((path, index) => path === blockedPaths[index]), 'migration preserves blocked URI metadata for diagnostics')
  storage.set(storage.KEYS.PHOTOS, [])
  storage.initialize()

  const createdPhotos = await albumService.saveImages(['emoji:🌷', 'local://offline-photo'], { date: '2026-09-27', tags: ['离线'] })
  check(createdPhotos.length === 2 && albumService.total() === 2, 'album create/save works')
  const duplicatePhotos = albumService.createMany([{ imagePath: 'local://offline-photo', date: '2026-09-27' }])
  check(duplicatePhotos.length === 0 && albumService.getLastError().code === 'duplicate_image_path', 'album service rejects duplicate managed image path')
  const tooManyAlbum = await albumService.saveImages(Array.from({ length: LIMITS.ALBUM_PHOTOS_PER_BATCH + 1 }, (_, index) => `local://too-many-${index}`), { date: '2026-09-27' })
  check(tooManyAlbum.length === 0 && albumService.getLastError().code === 'too_many_photos', 'album batch limit returns visible code')
  const tooManyRecipe = await recipeService.addPhotos(custom.recipeId, Array.from({ length: LIMITS.RECIPE_PHOTOS_PER_RECIPE + 1 }, (_, index) => `local://recipe-too-many-${index}`))
  check(!tooManyRecipe && recipeService.getLastError().code === 'too_many_photos', 'recipe photo limit returns visible code')
  check(albumService.groupByMonth().length === 1, 'album groups by month')
  check(withImageFlag(createdPhotos[0]).hasImage === false && withImageFlag(createdPhotos[1]).hasImage === true, 'media flags distinguish placeholder and real path')
  check(markImageError([withImageFlag(createdPhotos[1])], 0)[0].hasImage === false, 'media error falls back to placeholder')
  check(isImagePath(albumService.get(createdPhotos[1].photoId).imagePath), 'real photo path remains in metadata after reload')
  const ownPhoto = createdPhotos[0]
  check(albumService.remove(ownPhoto.photoId, activeUser.userId).ok, 'album owner can delete')
  check(albumService.remove(createdPhotos[1].photoId, 'another-user').reason === 'forbidden', 'album rejects other owner')

  chatService.clearMessages()
  const chat = chatService.sendMessage('今天一起吃饭吧')
  check(chat.ok && chat.messages.length >= 3, 'chat send/reply works')
  while (chatService.list().length < LIMITS.CHAT_MESSAGES) chatService.addMessage({ senderId: 'fixture-user', receiverId: 'batiao', content: `容量测试消息${chatService.list().length}`, type: 'text', isRead: true })
  const fullChats = chatService.list()
  const firstChatId = fullChats[0].messageId
  const lastChatId = fullChats[fullChats.length - 1].messageId
  const chatOverflow = chatService.sendMessage('超过容量的聊天')
  check(!chatOverflow.ok && chatOverflow.reason === 'chat_limit' && chatService.list().length === LIMITS.CHAT_MESSAGES, 'chat limit rejects a new transaction without dropping old records')
  check(chatService.list()[0].messageId === firstChatId && chatService.list()[chatService.list().length - 1].messageId === lastChatId, 'chat limit preserves first and last existing records')

  feedbackService.clear()
  for (let index = 0; index < LIMITS.FEEDBACK; index += 1) feedbackService.submit({ category: 'feature', content: `容量反馈${index}内容足够长` })
  const fullFeedback = feedbackService.list()
  const feedbackIds = fullFeedback.map((record) => record.feedbackId)
  const feedbackOverflow = feedbackService.submit({ category: 'feature', content: '超过容量的反馈内容足够长' })
  check(!feedbackOverflow.ok && feedbackOverflow.code === 'feedback_limit' && feedbackService.list().length === LIMITS.FEEDBACK, 'feedback limit rejects a new record without dropping old records')
  check(feedbackService.list().every((record) => feedbackIds.indexOf(record.feedbackId) >= 0), 'feedback limit preserves every existing record')

  const originalWx = global.wx
  global.wx = { getStorageSync: () => undefined, setStorageSync: () => {}, getStorageInfoSync: () => ({ currentSize: 10, limitSize: 1 }) }
  const quotaResult = storage.setChecked(storage.KEYS.SETTINGS, { oversized: 'quota' })
  check(!quotaResult.ok && quotaResult.error.code === 'storage_quota', 'storage quota failure is diagnosable')
  if (originalWx === undefined) delete global.wx
  else global.wx = originalWx

  storage.set(storage.KEYS.COUPLE, { coupleId: 'local-couple', partner: { userId: 'partner-1' }, anniversaryDate: historicalDate })
  userService.updateSettings({ emotionCareEnabled: true, notificationsEnabled: true })
  chatService.clearMessages()
  const care = chatService.sendMessage('我很失望')
  check(care.careMessage && care.careMessage.type === 'emotion_care', 'emotion care sends generalized message when enabled')
  userService.updateSettings({ notificationsEnabled: false })
  chatService.clearMessages()
  const muted = chatService.sendMessage('我很孤独')
  check(!muted.careMessage, 'notification switch suppresses emotion care')

  storage.set(storage.KEYS.CAT, { level: 1, feedCount: 0, chatCount: 0, exp: 0, mood: 50, hunger: 50, todayFeedCount: 0, lastFeedTime: 0 })
  const cat = catService.feed()
  check(cat.ok, 'cat feed works')
  const afterThree = [catService.feed(), catService.feed()]
  check(afterThree.every((result) => result.ok), 'cat allows three feeds')
  check(catService.feed().reason === 'daily_limit', 'cat enforces daily feed limit')

  recipeService.create({ name: '待清理菜谱', photos: ['local://recipe-file'] })
  await albumService.saveImages(['local://album-file'], { date: historicalDate })
  const originalRemoveImageChecked = storage.removeImageChecked
  storage.removeImageChecked = () => Promise.resolve({ ok: false, code: 'file_remove_failed', message: '图片清理失败' })
  const cleared = await userService.clearLocalData()
  storage.removeImageChecked = originalRemoveImageChecked
  check(cleared && !cleared.user && !cleared.ok && cleared.failedFiles.length >= 2, 'clear reports file cleanup failures without fake success')
  check(storage.list(storage.KEYS.CHATS).length > 0 && storage.list(storage.KEYS.PHOTOS).length > 0, 'failed clear preserves metadata for retry')
  const retried = await userService.clearLocalData()
  check(retried && retried.ok && retried.user && retried.user.nickname === '小主人', 'clear retry restores default user')
  check(storage.list(storage.KEYS.CHATS).length === 0, 'successful retry removes chats')
  check(storage.list(storage.KEYS.PHOTOS).length === 0, 'successful retry removes photos')
  check(feedbackService.list().length === 0, 'successful retry removes local feedback')
  console.log('SMOKE_LOCAL=PASS')
  console.log(`SCHEMA_VERSION=${storage.get(storage.KEYS.META, {}).schemaVersion}`)
  console.log(`RECIPES=${recipeService.ensureDefaults().length}`)
}

main().catch((error) => {
  console.error(`SMOKE_LOCAL=FAIL ${error.stack || error.message}`)
  process.exitCode = 1
})
